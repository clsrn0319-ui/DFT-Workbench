def rows(confidence=None, families=None, require_delta=False):
    """조건에 맞는 참조 항목만 고른다."""
    out = []
    for r in REFERENCE:
        if confidence and r[7] not in confidence:
            continue
        if families and r[6] not in families:
            continue
        if require_delta and r[5] is None:
            continue
        out.append(r)
    return out


def family_counts(subset=None) -> dict:
    counts: dict[str, int] = {}
    for r in (subset or REFERENCE):
        counts[r[6]] = counts.get(r[6], 0) + 1
    return counts
